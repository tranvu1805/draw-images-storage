setfs(16)

# y = -x - 1 - 1/(x+1): TCX y = -x - 1, TCĐ x = -1, CT (-2;2), CĐ (0;-2)
fig, ax = win('img056', (236, 200), 38)
axes(ax, (-5.74, 3.37), (-4.47, 5.0), xname=None, yname=None, origin=None)

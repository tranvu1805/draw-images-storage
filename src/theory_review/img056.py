f = lambda x: -x - 1 - 1 / (x + 1)
curve(ax, f, -5.6, -1.001, box=box)
curve(ax, f, -0.999, 3.5, box=box)
curve(ax, lambda x: -x - 1, -5.74, 3.5, lw=1.3, box=box)
vline(ax, -1, -4.47, 4.6, lw=1.3)
xt(ax, [1], [''])
T(ax, -0.4, 4.85, '$y$', fs=17)
T(ax, 3.1, -0.55, '$x$', fs=17)

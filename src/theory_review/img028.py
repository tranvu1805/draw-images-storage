from graphs_kit import *
setfs(16)

# y = -x - 1 - 1/(x+1): asymptotes x = -1, y = -x - 1; extrema (0;-2), (-2;2); centre (-1;0)
fig, ax = win('img028', (227, 180), (36, 35.5))
axes(ax, (-5.67, 3.36), (-4.5, 5.0), xname=None, yname=None, origin=None)
box = (-5.6, 3.45, -4.5, 4.68)
f = lambda x: -x - 1 - 1 / (x + 1)
curve(ax, f, -5.6, -1.001, box=box)
curve(ax, f, -0.999, 3.45, box=box)
curve(ax, lambda x: -x - 1, -5.6, 3.45, lw=1.3, box=box)
vline(ax, -1, -4.5, 4.68, lw=1.3)
xt(ax, [1], [''])
T(ax, 3.1, -0.5, '$x$')
T(ax, -0.45, 4.85, '$y$')
T(ax, -0.4, 0.4, '$O$')
T(ax, -1.42, -0.55, '$-1$')
T(ax, 0.97, -0.55, '$1$')
T(ax, -0.1, -1.05, '$-1$', ha='right')
T(ax, -0.1, -1.83, '$-2$', ha='right')
save(fig, 'img028')

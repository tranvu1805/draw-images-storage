from tabgeo_kit import *

P = {'D': (100, 28), 'C': (236, 28), 'A': (39, 94), 'B': (176, 95),
     "D'": (98, 143), "C'": (234, 144), "A'": (37, 209), "B'": (174, 210)}
P['O'] = ((P['A'][0] + P["C'"][0]) / 2, (P['A'][1] + P["C'"][1]) / 2)
G = Geo('img266', P, fs=14, lw=1.3)
G.edges("D-C A-D A-B B-C C-C' A-A' B-B' A'-B' B'-C'")
G.edges("D-D' D'-C' D'-A' A-C'", dashed=True)
for k in P:
    G.dot(k, r=4)
G.labs({'D': ('n', 12), 'C': ('ne', 12), 'A': ('w', 13), 'B': (-40, 14), "D'": (45, 15), "C'": (-30, 15),
        "A'": (230, 14), "B'": ('s', 13), 'O': (60, 11)})
G.save()

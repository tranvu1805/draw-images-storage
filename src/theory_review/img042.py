from graphs_kit import *
setfs(14)

# y = x - 1 + 1/(x - 1): TCĐ x=1, TCX y=x-1, CĐ (0;-2), CT (2;2)
fig, ax = win('img042', (137, 133), (21, 22))
axes(ax, (-5.1, 8.24), (-4.9, 5.9), xname=None, yname=None, origin=None)
box = (-4.5, 6.9, -4.9, 5.4)
f = lambda x: x - 1 + 1 / (x - 1)
curve(ax, f, -4.5, 0.999, box=box)
curve(ax, f, 1.001, 6.9, box=box)
curve(ax, lambda x: x - 1, -4.5, 6.9, lw=1.3, box=box)
vline(ax, 1, -4.9, 5.4, lw=1.3)
dash(ax, [(0, 2), (2, 2), (2, 0)])
yt(ax, [1, 2], ['', ''])
T(ax, -0.35, 5.6, '$y$', fs=15, ha='right')
T(ax, 8.0, -0.55, '$x$', fs=15)
T(ax, -0.35, 2.0, '$2$', ha='right')
T(ax, -0.35, 1.0, '$1$', ha='right')
T(ax, 0.3, 0.6, '$O$')
T(ax, -0.3, -0.95, '$-1$', ha='right')
T(ax, -0.25, -2.1, '$-2$', ha='right', bg=True)
T(ax, 1.3, -0.65, '$1$')
T(ax, 2.1, -0.65, '$2$')
save(fig, 'img042')

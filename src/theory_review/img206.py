from tabgeo_kit import *

P = {'B': (25, 142), 'C': (123, 142), 'D': (161, 122), 'A': (63, 122),
     "B'": (25, 46), "C'": (123, 46), "D'": (161, 26), "A'": (63, 26)}
G = Geo('img206', P, fs=13, lw=1.3)
G.edges("B-C C-D D-D' B-B' C-C' B'-C' C'-D' D'-A' A'-B'")
G.edges("A-B A-D A-A'", dashed=True)
for k in P:
    G.dot(k, r=3.5)
G.labs({'A': (160, 12), 'B': (225, 13), 'C': (290, 13), 'D': (-30, 13), "A'": (100, 13), "B'": (160, 14),
        "C'": (-40, 13), "D'": (30, 12)})
G.save()

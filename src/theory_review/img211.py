from graphs_kit import *
setfs(16)

# on [-3;1]: segment from (-3;5) to (-2;-1), then y = 3 - x^2 from (-2;-1) through (0;3) to (1;2)
fig, ax = win('img211', (172, 300), (42, 41.5))
axes(ax, (-3.43, 2.86), (-1.88, 6.22), xname=None, yname=None, origin=None, lw=1.6, head=8)
dash(ax, [(-3, 0), (-3, 5), (0, 5)], lw=1.5, ls=(0, (5, 4)))
dash(ax, [(-2, 0), (-2, -1), (0, -1)], lw=1.5, ls=(0, (5, 4)))
dash(ax, [(1, 0), (1, 2), (0, 2)], lw=1.5, ls=(0, (5, 4)))
seg(ax, [(-3, 5), (-2, -1)], lw=2.0)
curve(ax, lambda x: 3 - x**2, -2, 1, lw=2.0)
T(ax, 0.35, 6.0, '$y$', fs=17)
T(ax, 2.7, 0.45, '$x$', fs=17)
T(ax, 0.42, 5.0, '$5$')
T(ax, 0.3, 3.4, '$3$')
T(ax, -0.25, 2.0, '$2$', ha='right')
T(ax, -1.93, 0.5, '$-2$', fs=14)
T(ax, -3.0, -0.45, '$-3$')
T(ax, 0.35, -0.45, '$O$')
T(ax, 1.0, -0.45, '$1$')
T(ax, 0.42, -1.05, '$-1$')
save(fig, 'img211')

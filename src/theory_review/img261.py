# on [-2;3]: smooth curve from (-2;-3) up to CĐ (-1;4), down to (1;-2), then a segment to (3;3); m = -3, M = 4
fig, ax = win('img261', (143, 95), (35.5, 17.2))
axes(ax, (-3.41, 4.11), (-4.07, 5.06), xname=None, yname=None, origin=None, lw=1.2, head=8)

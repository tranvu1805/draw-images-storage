setfs(13)

# y = x^3 - 3x: CĐ (-1;2), CT (1;-2)
fig, ax = win('img231', (123, 111), (31, 26.75))
axes(ax, (-3.97, 3.77), (-3.63, 4.07), xname=None, yname=None, origin=None, lw=1.6, head=8)

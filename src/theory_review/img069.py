from graphs_kit import *
setfs(15)

# y = -1 + 2/(x + 1) = (1 - x)/(1 + x): TCĐ x = -1, TCN y = -1; through (0;1), (1;0), (-3;-2), (-2;-3)
fig, ax = win('img069', (160, 84), (35.5, 27))
axes(ax, (-4.42, 2.68), (-4.48, 2.93), xname=None, yname=None, origin=None, lw=1.1)
box = (-4.42, 2.54, -4.48, 2.85)
hline(ax, -1, -4.42, 2.54, lw=1.3)
vline(ax, -1, -4.48, 2.85, lw=1.3)
dash(ax, [(-3, 0), (-3, -2), (0, -2)])
dash(ax, [(-2, 0), (-2, -3), (0, -3)])
f = lambda x: -1 + 2 / (x + 1)
curve(ax, f, -4.42, -1.001, box=box)
curve(ax, f, -0.999, 2.54, box=box)
T(ax, 0.32, 2.75, '$y$', fs=16)
T(ax, 2.55, -0.35, '$x$', fs=16)
T(ax, -0.25, 1.0, '$1$', ha='right')
for x, s in [(-3.15, '$-3$'), (-2.2, '$-2$'), (-1.25, '$-1$'), (1.0, '$1$')]:
    T(ax, x, -0.45, s, bg=True)
T(ax, -0.3, -0.45, '$O$')
T(ax, -0.15, -1.4, '$-1$', ha='right')
T(ax, -0.15, -2.4, '$-2$', ha='right')
T(ax, -0.15, -3.4, '$-3$', ha='right')
save(fig, 'img069')
